/** Russian plural: 1 год, 2–4 года, 5 лет (11–14 лет, 21 год, 22 года). */
const plural = (n: number, one: string, few: string, many: string) => {
  const d = n % 10;
  const t = n % 100;
  if (d === 1 && t !== 11) return one;
  if (d >= 2 && d <= 4 && (t < 12 || t > 14)) return few;
  return many;
};
const years = (n: number) => `${n} ${plural(n, "год", "года", "лет")}`;
const nod = (n: number) => plural(n, "нода", "ноды", "нод");

